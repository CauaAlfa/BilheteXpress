    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        String email = txtEmail.getText().trim();

        if (email.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Insira o email.", "Erro", JOptionPane.ERROR_MESSAGE);
            return;
        }

        codigoEnviado = EmailSender.gerarCodigoRecuperacao();
        EmailSender.enviarCodigoRecuperacao(email, codigoEnviado);

        JOptionPane.showMessageDialog(this, "Código de recuperação enviado para o email fornecido.", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
        btnVerificarCodigo.setEnabled(true);
    }//GEN-LAST:event_jButton1ActionPerformed

    private void btnVerificarCodigoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVerificarCodigoActionPerformed
    
        String codigoDigitado = txtCodigoRecuperacao.getText().trim();

        if (codigoDigitado.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Insira o código de recuperação.", "Erro", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (codigoDigitado.equals(codigoEnviado)) {
            JOptionPane.showMessageDialog(this, "Código verificado! Pode inserir sua nova senha.", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            pfNovaSenha.setEnabled(true);
            btnAtualizarSenha.setEnabled(true);
        } else {
            JOptionPane.showMessageDialog(this, "Código de recuperação incorreto.", "Erro", JOptionPane.ERROR_MESSAGE);
        }


    }//GEN-LAST:event_btnVerificarCodigoActionPerformed

    private void btnAtualizarSenhaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarSenhaActionPerformed

        String novaSenha = new String(pfNovaSenha.getPassword()).trim();
        String email = txtEmail.getText().trim();

        if (novaSenha.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Insira a nova senha.", "Erro", JOptionPane.ERROR_MESSAGE);
            return;
        }

        UsuarioDAO usuarioDAO = new UsuarioDAO();
        boolean senhaAtualizada = usuarioDAO.atualizarSenha(email, novaSenha);

        if (senhaAtualizada) {
            JOptionPane.showMessageDialog(this, "Senha atualizada com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(this, "Erro ao atualizar a senha.", "Erro", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_btnAtualizarSenhaActionPerformed

